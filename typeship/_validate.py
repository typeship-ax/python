"""Runtime validation of JSON bodies against the spec's own schemas.

Generated by typeship — https://typeship.dev — do not edit by hand.

Zero dependencies: the schema tables are plain data in _schemas.py and the
validator below is the only code that reads them.
"""
from __future__ import annotations

import re
from typing import Any, List, Mapping, Optional

from ._errors import TypeshipError

MAX_VIOLATIONS = 50


class Violation:
    """One place the payload disagreed with the spec."""

    __slots__ = ("path", "message")

    def __init__(self, path: str, message: str) -> None:
        self.path = path
        self.message = message

    def __repr__(self) -> str:
        return "%s %s" % (self.path, self.message)


class ValidationError(TypeshipError):
    """A request or response body did not match the spec's schema.

    Only raised when the client is constructed with validate=True; the
    default is off, and validate="warn" logs instead of raising.
    """

    def __init__(self, direction: str, violations: List["Violation"]) -> None:
        shown = "; ".join(str(v) for v in violations[:3])
        extra = " (+%d more)" % (len(violations) - 3) if len(violations) > 3 else ""
        super().__init__("%s body failed schema validation: %s%s" % (direction, shown, extra))
        self.direction = direction
        self.violations = violations


def _json_type(value: Any) -> str:
    if value is None:
        return "null"
    if isinstance(value, bool):  # before int: bool is an int in Python
        return "boolean"
    if isinstance(value, str):
        return "string"
    if isinstance(value, int):
        return "integer"
    if isinstance(value, float):
        return "number"
    if isinstance(value, (list, tuple)):
        return "array"
    if isinstance(value, dict):
        return "object"
    return "unknown"


def _type_matches(value: Any, expected: str) -> bool:
    actual = _json_type(value)
    if expected == "number":
        return actual in ("number", "integer")
    if expected == "integer":
        return actual == "integer"
    return actual == expected


def validate_against_schema(
    value: Any,
    schema: Any,
    path: str,
    out: List[Violation],
    defs: Optional[Mapping[str, Any]] = None,
) -> None:
    """Check a value against the emitted JSON Schema subset.

    Constraints outside the subset (formats, multipleOf, not, ...) are
    ignored: validation may miss drift, but must never reject valid traffic.
    """
    if len(out) >= MAX_VIOLATIONS or not isinstance(schema, dict):
        return

    # Named components are deduplicated into DEFS; recursion is bounded by
    # the data's own depth, so cyclic schemas terminate.
    ref = schema.get("$ref")
    if isinstance(ref, str):
        validate_against_schema(value, (defs or {}).get(ref), path, out, defs)
        return

    for sub in schema.get("allOf") or []:
        validate_against_schema(value, sub, path, out, defs)
    variants = schema.get("anyOf") or schema.get("oneOf")
    if variants:
        matched = False
        for sub in variants:
            scratch: List[Violation] = []
            validate_against_schema(value, sub, path, scratch, defs)
            if not scratch:
                matched = True
                break
        if not matched:
            out.append(Violation(path, "matches none of the allowed variants"))

    declared = schema.get("type")
    if declared is not None:
        allowed = list(declared) if isinstance(declared, list) else [declared]
        if schema.get("nullable") is True and "null" not in allowed:
            allowed.append("null")
        if not any(_type_matches(value, t) for t in allowed):
            out.append(Violation(path, "expected %s, got %s" % (" | ".join(allowed), _json_type(value))))
            return  # the remaining constraints assume the right type
    if value is None:
        return

    if "enum" in schema and value not in schema["enum"]:
        out.append(Violation(path, "not one of the allowed enum values"))
    if "const" in schema and value != schema["const"]:
        out.append(Violation(path, "does not equal the required constant"))

    if isinstance(value, (int, float)) and not isinstance(value, bool):
        minimum = schema.get("minimum")
        maximum = schema.get("maximum")
        if isinstance(minimum, (int, float)) and value < minimum:
            out.append(Violation(path, "below minimum %s" % minimum))
        if isinstance(maximum, (int, float)) and value > maximum:
            out.append(Violation(path, "above maximum %s" % maximum))

    if isinstance(value, str):
        min_length = schema.get("minLength")
        max_length = schema.get("maxLength")
        if isinstance(min_length, int) and len(value) < min_length:
            out.append(Violation(path, "shorter than minLength %d" % min_length))
        if isinstance(max_length, int) and len(value) > max_length:
            out.append(Violation(path, "longer than maxLength %d" % max_length))
        pattern = schema.get("pattern")
        if isinstance(pattern, str):
            try:
                if re.search(pattern, value) is None:
                    out.append(Violation(path, "does not match pattern"))
            except re.error:
                pass  # an invalid pattern in the spec must not fail valid data

    if isinstance(value, list):
        min_items = schema.get("minItems")
        max_items = schema.get("maxItems")
        if isinstance(min_items, int) and len(value) < min_items:
            out.append(Violation(path, "fewer than minItems %d" % min_items))
        if isinstance(max_items, int) and len(value) > max_items:
            out.append(Violation(path, "more than maxItems %d" % max_items))
        items = schema.get("items")
        if items:
            for index, item in enumerate(value):
                if len(out) >= MAX_VIOLATIONS:
                    break
                validate_against_schema(item, items, "%s[%d]" % (path, index), out, defs)

    if isinstance(value, dict):
        for key in schema.get("required") or []:
            if key not in value:
                out.append(Violation(path, "missing required property %r" % key))
        properties = schema.get("properties")
        if isinstance(properties, dict):
            for key, sub in properties.items():
                if key in value:
                    validate_against_schema(value[key], sub, "%s.%s" % (path, key), out, defs)
            if schema.get("additionalProperties") is False:
                for key in value:
                    if key not in properties:
                        out.append(Violation(path, "unexpected property %r" % key))
